#!/usr/bin/env python3
"""INKBOLT build.

  python3 tools/build.py            -> zones bundle, dev page, upload build, single-file Play build

Outputs
  Source/src/data/zones.gen.js      zone ASCII maps as IB.ZONE_MAPS (loaded by the dev page and bundles)
  Source/dev.html                   unbundled dev page (serve Source/ over http)
  Source/dist/upload/               index.html + three.min.js + three-LICENSE.txt (plain build, no SDK)
  <repo>/Play Inkbolt.html          single file: three.js, code, CSS and font inlined; runs offline from disk
"""
import base64, gzip, json, os, re, shutil, sys

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(SRC)


def read(p):
    with open(os.path.join(SRC, p), encoding='utf-8') as f:
        return f.read()


def write(p, s):
    p = os.path.join(SRC, p) if not os.path.isabs(p) else p
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8') as f:
        f.write(s)


# every Source/assets/fps-<family>.glb is a family (common, weapons, bots, kit-<theme>)
ASSETS = {f[4:-4]: f for f in sorted(os.listdir(os.path.join(SRC, 'assets'))) if f.startswith('fps-') and f.endswith('.glb')}
UMD = '(typeof window !== "undefined" ? (window.IB = window.IB || {}) : (globalThis.IB = globalThis.IB || {}))'


def generated_data():
    # asset list
    write('src/data/assets.gen.js', '/* generated by tools/build.py; do not edit */\n(function (IB) { IB.ASSET_FILES = ' + json.dumps(ASSETS) + '; })' + UMD + ';\n')
    # theme files bundled in name order
    d = os.path.join(SRC, 'src/data/themes')
    parts = ['/* generated by tools/build.py from src/data/themes/*.js; do not edit */']
    for name in sorted(os.listdir(d)):
        if name.endswith('.js'):
            parts.append('/* ---- themes/%s ---- */\n' % name + open(os.path.join(d, name), encoding='utf-8').read())
    write('src/data/themes.gen.js', '\n'.join(parts) + '\n')


def zones_bundle():
    d = os.path.join(SRC, 'src/data/zones')
    maps = {}
    for name in sorted(os.listdir(d)):
        if name.endswith('.txt'):
            with open(os.path.join(d, name), encoding='utf-8') as f:
                maps[name[:-4]] = f.read()
    js = ('/* generated by tools/build.py from src/data/zones/*.txt; do not edit */\n'
          '(function (IB) { IB.ZONE_MAPS = ' + json.dumps(maps, indent=1) + '; })'
          '(typeof window !== "undefined" ? (window.IB = window.IB || {}) : (globalThis.IB = globalThis.IB || {}));\n')
    write('src/data/zones.gen.js', js)
    return maps


def script_list(html):
    block = re.search(r'<!--BUILD:JS-->(.*?)<!--/BUILD:JS-->', html, re.S).group(1)
    return re.findall(r'<script src="([^"]+)"></script>', block)


def inline_js(code):
    return code.replace('</script', '<\\/script')


def bundle(platform='plain', standalone=False, split=None):
    # split: a folder; the GLB data goes into glb-<n>.js files there (each under ~6 MB, loaded by <script src> before
    # the game), so the page itself stays small (the published artifact: page and each file under 16 MB)
    html = read('src/index.src.html')
    # every stylesheet linked in the BUILD:CSS block, in order; every vendored font url('../../vendor/fonts/X.woff2')
    # is inlined as a data URL
    block = re.search(r'<!--BUILD:CSS-->(.*?)<!--/BUILD:CSS-->', html, re.S).group(1)
    css = '\n'.join(read(h) for h in re.findall(r'<link rel="stylesheet" href="([^"]+)">', block))

    def font_url(m):
        data = base64.b64encode(open(os.path.join(SRC, 'vendor/fonts', m.group(1)), 'rb').read()).decode()
        return "url(data:font/woff2;base64," + data + ")"
    css = re.sub(r"url\('\.\./\.\./vendor/fonts/([^']+\.woff2)'\)", font_url, css)
    html = re.sub(r'<!--BUILD:CSS-->.*?<!--/BUILD:CSS-->', lambda m: '<style>\n' + css + '\n</style>', html, flags=re.S)
    scripts = script_list(html)
    game = ['window.__PLATFORM__ = %s;' % json.dumps(platform)]
    if standalone:   # every GLB embedded as base64 (brief 4.2); decoded with GLTFLoader.parse
        data = {}
        for fam, fn in ASSETS.items():
            # gzip before base64: GLBs shrink 4-7x; the game inflates them with the browser's DecompressionStream
            data[fam] = base64.b64encode(gzip.compress(open(os.path.join(SRC, 'assets', fn), 'rb').read(), 9, mtime=0)).decode()
        if split:
            parts, cur, size = [], {}, 0
            for fam in data:
                if cur and size + len(data[fam]) > 6e6:
                    parts.append(cur); cur, size = {}, 0
                cur[fam] = data[fam]; size += len(data[fam])
            parts.append(cur)
            data_tags = []
            for i, part in enumerate(parts):
                fn = 'glb-%d.js' % (i + 1)
                write(os.path.join(split, fn), 'window.IB = window.IB || {}; IB.GLB_GZ = true; IB.GLB_DATA = IB.GLB_DATA || {};\n' +
                      ''.join('IB.GLB_DATA[%s] = %s;\n' % (json.dumps(k), json.dumps(v)) for k, v in part.items()))
                data_tags.append('<script src="%s"></script>' % fn)
        else:
            game.append('window.IB = window.IB || {}; IB.GLB_GZ = true; IB.GLB_DATA = ' + json.dumps(data) + ';')
    # tactical look detail textures (assets/tex/*.webp, plan Stage 5B.4): data URLs in IB.TEX_DATA (a side file in
    # the artifact build); the dev and upload pages load them from assets/tex/ instead
    tex_tags = []
    if standalone:
        tdir = os.path.join(SRC, 'assets', 'tex')
        tex = {}
        if os.path.isdir(tdir):
            for fn in sorted(os.listdir(tdir)):
                if fn.endswith('.webp'):
                    tex[fn] = 'data:image/webp;base64,' + base64.b64encode(open(os.path.join(tdir, fn), 'rb').read()).decode()
        line = 'window.IB = window.IB || {}; IB.TEX_DATA = ' + json.dumps(tex) + ';'
        if split:
            write(os.path.join(split, 'tex-1.js'), line + '\n')
            tex_tags.append('<script src="tex-1.js"></script>')
        else:
            game.append(line)
    vendor_tags = []
    for s in scripts:
        if s.startswith('vendor/'):
            if standalone:
                vendor_tags.append('<script>' + inline_js(read(s)) + '</script>')
            else:
                vendor_tags.append('<script src="%s"></script>' % os.path.basename(s))
        else:
            game.append('/* ---- %s ---- */\n%s' % (s, read(s)))
    if standalone and split:
        vendor_tags += data_tags + tex_tags
    js = '\n'.join(vendor_tags) + '\n<script>\n' + inline_js('\n'.join(game)) + '\n</script>'
    html = re.sub(r'<!--BUILD:JS-->.*?<!--/BUILD:JS-->', lambda m: js, html, flags=re.S)
    return html


def main():
    zones_bundle()
    generated_data()
    # dev page: same markup, paths resolve from Source/
    write('dev.html', read('src/index.src.html'))
    # upload build (plain)
    up = os.path.join(SRC, 'dist/upload')
    if os.path.isdir(up):
        shutil.rmtree(up)
    os.makedirs(up)
    write(os.path.join(up, 'index.html'), bundle('plain', False))
    for f in ('three.min.js', 'three-LICENSE.txt', 'GLTFLoader.js', 'BufferGeometryUtils.js'):
        shutil.copy(os.path.join(SRC, 'vendor', f), up)
    os.makedirs(os.path.join(up, 'assets'))
    for fn in ASSETS.values():
        shutil.copy(os.path.join(SRC, 'assets', fn), os.path.join(up, 'assets'))
    if os.path.isdir(os.path.join(SRC, 'assets', 'tex')):
        shutil.copytree(os.path.join(SRC, 'assets', 'tex'), os.path.join(up, 'assets', 'tex'))
    # single-file offline build
    play = os.path.join(ROOT, 'Play Inkbolt.html')
    write(play, bundle('plain', True))
    # published artifact build: the single-file game with its model data in side files
    art = os.path.join(SRC, 'dist/artifact')
    if os.path.isdir(art):
        shutil.rmtree(art)
    os.makedirs(art)
    write(os.path.join(art, 'index.html'), bundle('plain', True, art))
    for p in [play, os.path.join(up, 'index.html')] + [os.path.join(SRC, 'assets', f) for f in ASSETS.values()]:
        print('%-60s %8.1f KB' % (os.path.relpath(p, ROOT), os.path.getsize(p) / 1024))


if __name__ == '__main__':
    sys.exit(main())
