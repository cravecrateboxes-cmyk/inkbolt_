#!/usr/bin/env python3
"""Surface table generator (tactical look plan, Stage 5A.1-5A.3, started in Stage 2.2).

    python3 Source/tools/gen_surfaces.py            write blender/palettes.gen.json, src/data/surfaces.gen.js and
                                                    one labelled swatch sheet per family in Source/dist/surfaces/
    python3 Source/tools/gen_surfaces.py --print kit-metro [kit-mall ...]   list cells by class (review)

Every palette cell of every family gets one class from blender/surface_classes.py. Run it again whenever a
fam_*.py palette changes (trap T19); tests/unit/surfaces.test.js checks the two generated files agree.
"""
import importlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(HERE)
BL = os.path.join(SRC, 'blender')
sys.path.insert(0, BL)


def load():
    cwd = os.getcwd(); os.chdir(BL)
    try:
        import ib_lib
        fams = {}
        for f in sorted(os.listdir(BL)):
            if f.startswith('fam_') and f.endswith('.py'):
                m = importlib.import_module(f[:-3]); fams[m.FAMILY] = f
    finally:
        os.chdir(cwd)
    import surface_classes as SC
    return {k: list(ib_lib.PALETTES[k]) for k in sorted(fams)}, SC


def table(pal, SC):
    out = {}
    for fam, cells in pal.items():
        ov = SC.OVERRIDES.get(fam, {})
        names = [n for n, _ in cells]
        bad = [n for n in ov if n not in names]
        if bad:
            raise SystemExit('surface_classes.OVERRIDES[%r] names cells that do not exist: %s' % (fam, bad))
        cls, emit = [], []
        for n in names:
            c, e = SC.classify(fam, n)
            cls.append(c); emit.append(round(float(e), 2))
        out[fam] = {'names': names, 'cls': cls, 'emit': emit, 'col': [int(h.lstrip('#')[:6], 16) for _, h in cells]}
    return out


def swatches(pal, tab, SC):
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return
    d = os.path.join(SRC, 'dist', 'surfaces'); os.makedirs(d, exist_ok=True)
    for fam, cells in pal.items():
        im = Image.new('RGB', (8 * 150, 8 * 60), (20, 20, 24)); dr = ImageDraw.Draw(im)
        for i, (n, hx) in enumerate(cells):
            x, y = (i % 8) * 150, (i // 8) * 60
            rgb = tuple(int(hx.lstrip('#')[k:k + 2], 16) for k in (0, 2, 4))
            dr.rectangle([x + 2, y + 2, x + 147, y + 57], fill=rgb)
            lum = 0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]
            c = tab[fam]['cls'][i]; e = tab[fam]['emit'][i]
            t = (0, 0, 0) if lum > 128 else (255, 255, 255)
            dr.text((x + 6, y + 6), n, fill=t)
            dr.text((x + 6, y + 30), SC.CLASS_NAMES[c] + (' %.2g' % e if c == 15 else ''), fill=t)
        im.save(os.path.join(d, fam + '.png'))


def main(argv):
    pal, SC = load()
    tab = table(pal, SC)
    if argv and argv[0] == '--print':
        for fam in argv[1:]:
            t = tab[fam]; by = {}
            for n, c, e in zip(t['names'], t['cls'], t['emit']):
                by.setdefault(c, []).append(n + ('*%g' % e if c == 15 else ''))
            print('== ' + fam)
            for c in sorted(by):
                print('  %-13s %s' % (SC.CLASS_NAMES[c], ' '.join(by[c])))
        return
    json.dump({k: [[n, h] for n, h in v] for k, v in pal.items()}, open(os.path.join(BL, 'palettes.gen.json'), 'w'), separators=(',', ':'))
    js = ['/* GENERATED by Source/tools/gen_surfaces.py from blender/surface_classes.py and the fam_*.py palettes.',
          '   Do not edit. family -> { names: palette cell names, cls: surface class per cell, emit: light weight, col: cell colour }.',
          '   Classes: ' + ', '.join('%d %s' % (i, n) for i, n in enumerate(SC.CLASS_NAMES)) + '. */',
          '(function (IB) {',
          '  IB.SURFACE_CLASSES = ' + json.dumps([{'name': n, 'gloss': g, 'metal': m} for n, (g, m) in zip(SC.CLASS_NAMES, SC.CLASS_GM)], separators=(',', ':')) + ';',
          '  IB.SURFACES = {']
    fams = sorted(tab)
    for i, fam in enumerate(fams):
        js.append('    %s: %s%s' % (json.dumps(fam), json.dumps(tab[fam], separators=(',', ':')), ',' if i < len(fams) - 1 else ''))
    js += ['  };', '})(typeof window !== \'undefined\' ? (window.IB = window.IB || {}) : (globalThis.IB = globalThis.IB || {}));', '']
    open(os.path.join(SRC, 'src', 'data', 'surfaces.gen.js'), 'w').write('\n'.join(js))
    swatches(pal, tab, SC)
    n = sum(len(v['names']) for v in tab.values())
    print('surfaces: %d families, %d cells, %d emissive' % (len(tab), n, sum(c == 15 for v in tab.values() for c in v['cls'])))


if __name__ == '__main__':
    main(sys.argv[1:])
