  // the paint scheme follows what is in the room (cached on the grid)
  function scheme(grid) {
    if (grid._lrScheme) return grid._lrScheme;
    var s = '1';
    for (var r = 0; r < grid.h && s === '1'; r++) for (var c = 0; c < grid.w; c++) {
      var ch = grid.at(c, r);
      if (ch === 'R') { s = '3'; break; }
      if (ch === 'D') s = '2';
    }
    grid._lrScheme = s;
    return s;
  }
